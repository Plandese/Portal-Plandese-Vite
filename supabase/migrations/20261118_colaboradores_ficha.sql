-- Ficha de validades/identificação dos colaboradores (dados sensíveis: só quem tem capítulo RH)
create table if not exists public.colaboradores_ficha (
  numero integer primary key references public.colaboradores(numero) on delete cascade,
  nacionalidade text,
  id_tipo text check (id_tipo in ('CC','R','P')),
  id_numero text,
  id_validade date,
  admissao date,
  fa_data date,
  epi_data date,
  email text,
  pasta text,
  atualizado_em timestamptz not null default now()
);
alter table public.colaboradores_ficha enable row level security;
drop policy if exists ler on public.colaboradores_ficha;
drop policy if exists inserir on public.colaboradores_ficha;
drop policy if exists alterar on public.colaboradores_ficha;
create policy ler on public.colaboradores_ficha for select to authenticated
  using (fn_cap('rh') and not fn_sec_all_off(array['colaboradores']));
create policy inserir on public.colaboradores_ficha for insert to authenticated
  with check (fn_cap('rh') and not fn_sec_all_off(array['colaboradores']));
create policy alterar on public.colaboradores_ficha for update to authenticated
  using (fn_cap('rh') and not fn_sec_all_off(array['colaboradores']))
  with check (fn_cap('rh') and not fn_sec_all_off(array['colaboradores']));
grant select, insert, update on public.colaboradores_ficha to authenticated;

