-- RLS: só o próprio (por username) lê ou escreve; nem os administradores acedem.
create table if not exists public.carteira_encomendas (
  id bigint generated always as identity primary key,
  ano int not null,
  cc text,
  empreitada text not null,
  cliente text not null,
  valor_sem_iva numeric(14,2) not null,
  prazo_meses numeric(5,1)
);
create table if not exists public.carteira_faturacao (
  id bigint generated always as identity primary key,
  ano int not null,
  mes int not null check (mes between 1 and 12),
  cc text not null,
  montante_sem_iva numeric(14,2) not null,
  montante_com_iva numeric(14,2) not null,
  data_emissao date not null
);
alter table public.carteira_encomendas enable row level security;
alter table public.carteira_faturacao enable row level security;
revoke all on public.carteira_encomendas, public.carteira_faturacao from anon;
drop policy if exists so_david on public.carteira_encomendas;
drop policy if exists so_david on public.carteira_faturacao;
create policy so_david on public.carteira_encomendas for all to authenticated
  using (public.fn_my_username() = 'david.mosca') with check (public.fn_my_username() = 'david.mosca');
create policy so_david on public.carteira_faturacao for all to authenticated
  using (public.fn_my_username() = 'david.mosca') with check (public.fn_my_username() = 'david.mosca');

