-- Sistema de teste das guias de remessa, SEPARADO do portal: tabelas próprias (gt_*), motor próprio e página própria (guias-teste.html).
-- Nada daqui aparece nas páginas do portal e nada do portal é alterado pelo teste. As faturas Secil reais são COPIADAS (botão «Importar faturas»).

create table if not exists gt_faturas (
  id bigint generated by default as identity primary key,
  origem_id bigint,                         -- id da fatura real de onde foi copiada (null = fatura criada só para o teste)
  fornecedor text, nif text, numero text, data date, data_pag date,
  base numeric, iva numeric, total numeric, status text, centro_custo text,
  linhas jsonb not null default '[]'::jsonb,
  guias_ref jsonb not null default '[]'::jsonb,
  ficheiro text, notas text,
  teste boolean not null default false,
  criado_em timestamptz default now(), criado_por text
);
create unique index if not exists gt_faturas_origem on gt_faturas (origem_id) where origem_id is not null;

create table if not exists gt_guias (like guias_remessa including all);
alter table gt_guias drop constraint if exists gt_guias_fatura_id_fkey;
alter table gt_guias add constraint gt_guias_fatura_id_fkey foreign key (fatura_id) references gt_faturas(id) on delete set null;

alter table gt_faturas enable row level security;
alter table gt_guias enable row level security;
drop policy if exists gt_faturas_ler on gt_faturas;
create policy gt_faturas_ler on gt_faturas for select to authenticated using (fn_my_role() = any (array['admin','financeiro','diretor_obra']) or fn_cap('fin'));
drop policy if exists gt_faturas_admin on gt_faturas;
create policy gt_faturas_admin on gt_faturas for all to authenticated using (fn_my_role() = 'admin') with check (fn_my_role() = 'admin');
drop policy if exists gt_guias_ler on gt_guias;
create policy gt_guias_ler on gt_guias for select to authenticated using (fn_my_role() = any (array['admin','financeiro','diretor_obra']) or fn_cap('fin'));
drop policy if exists gt_guias_inserir on gt_guias;
create policy gt_guias_inserir on gt_guias for insert to authenticated with check (criado_por = fn_my_username() and (fn_my_role() = any (array['admin','financeiro','diretor_obra']) or fn_cap('fin')));
drop policy if exists gt_guias_alterar on gt_guias;
create policy gt_guias_alterar on gt_guias for update to authenticated using (fn_my_role() = any (array['admin','financeiro','diretor_obra']) or fn_cap('fin')) with check (fn_my_role() = any (array['admin','financeiro','diretor_obra']) or fn_cap('fin'));
drop policy if exists gt_guias_apagar on gt_guias;
create policy gt_guias_apagar on gt_guias for delete to authenticated using (fn_my_role() = 'admin');

-- Cópia inicial: faturas Secil (fora de janeiro–maio de 2026) + faturas de teste; guias já carregadas
insert into gt_faturas (id, origem_id, fornecedor, nif, numero, data, data_pag, base, iva, total, status, centro_custo, linhas, guias_ref, ficheiro, notas, teste, criado_em, criado_por)
  select f.id, case when f.teste then null else f.id end, f.fornecedor, f.nif, f.numero, f.data, f.data_pag, f.base, f.iva, f.total, f.status, f.centro_custo,
         coalesce(f.linhas, '[]'::jsonb), coalesce(f.guias_ref, '[]'::jsonb), f.ficheiro, f.notas, f.teste, f.criado_em, f.criado_por
  from faturas f
  where f.fornecedor ilike '%secil%' and (f.data is null or f.data < '2026-01-01' or f.data > '2026-05-31')
    and not exists (select 1 from gt_faturas g where g.id = f.id);
select setval(pg_get_serial_sequence('gt_faturas', 'id'), greatest(100000, (select coalesce(max(id), 0) from gt_faturas)));

do $do$ declare cols text; begin
  select string_agg(quote_ident(attname), ', ' order by attnum) into cols from pg_attribute
    where attrelid = 'public.guias_remessa'::regclass and attnum > 0 and not attisdropped and attgenerated = '';
  execute format('insert into gt_guias (%1$s) overriding system value select %1$s from guias_remessa g where not exists (select 1 from gt_guias x where x.id = g.id)', cols);
end $do$;
select setval(pg_get_serial_sequence('gt_guias', 'id'), greatest(1000, (select coalesce(max(id), 0) from gt_guias)));

-- O que era só do teste sai das tabelas reais
delete from guias_remessa where id in (select id from gt_guias);
delete from faturas where teste = true and id in (select id from gt_faturas);

-- Motor próprio: cópia do motor do portal apontada às tabelas de teste
do $do$ declare d text; begin
  d := pg_get_functiondef('public.fn_sync_preco(text,date,text)'::regprocedure);
  d := regexp_replace(d, '\mfaturas\M', 'gt_faturas', 'g');
  d := replace(d, 'fn_sync_preco', 'gt_sync_preco');
  execute d;
  d := pg_get_functiondef('public.fn_sincronizar_guias(text)'::regprocedure);
  d := regexp_replace(d, '\mguias_remessa\M', 'gt_guias', 'g');
  d := regexp_replace(d, '\mfaturas\M', 'gt_faturas', 'g');
  d := replace(d, 'fn_sincronizar_guias', 'gt_sincronizar_guias');
  d := replace(d, 'fn_sync_preco', 'gt_sync_preco');
  d := replace(d, '7712001', '7712002');
  execute d;
end $do$;
revoke all on function gt_sincronizar_guias(text) from public, anon;
grant execute on function gt_sincronizar_guias(text) to authenticated, service_role;

create or replace function gt_trg_sincronizar() returns trigger language plpgsql security definer set search_path = public as $$
begin
  begin perform gt_sincronizar_guias(); exception when others then raise warning 'gt_sincronizar: %', sqlerrm; end;
  return null;
end $$;
drop trigger if exists gt_guias_sincronizar on gt_guias;
create trigger gt_guias_sincronizar after insert or update of linhas, numero, data, obra_nome, nif, sync_bloqueada on gt_guias
  for each row when (new.fatura_id is null) execute function gt_trg_sincronizar();
drop trigger if exists gt_faturas_sincronizar on gt_faturas;
create trigger gt_faturas_sincronizar after insert or update of guias_ref, linhas, base, data, centro_custo, status, nif on gt_faturas
  for each row execute function gt_trg_sincronizar();

-- Copia (e mantém atualizadas) as faturas Secil reais para o sistema de teste. Só lê da tabela real.
create or replace function gt_importar_faturas() returns jsonb language plpgsql security definer set search_path = public as $$
declare n_novas int; n_atual int;
begin
  if not (fn_my_role() = any (array['admin','financeiro','diretor_obra']) or fn_cap('fin')) then raise exception 'Sem permissão'; end if;
  insert into gt_faturas (origem_id, fornecedor, nif, numero, data, data_pag, base, iva, total, status, centro_custo, linhas, guias_ref, ficheiro, notas, teste, criado_em, criado_por)
    select f.id, f.fornecedor, f.nif, f.numero, f.data, f.data_pag, f.base, f.iva, f.total, f.status, f.centro_custo, coalesce(f.linhas, '[]'::jsonb), coalesce(f.guias_ref, '[]'::jsonb), f.ficheiro, f.notas, false, f.criado_em, f.criado_por
    from faturas f
    where f.fornecedor ilike '%secil%' and f.centro_custo like 'O065%' and not f.teste and (f.data is null or f.data < '2026-01-01' or f.data > '2026-05-31')
      and not exists (select 1 from gt_faturas g where g.origem_id = f.id);
  get diagnostics n_novas = row_count;
  update gt_faturas g set fornecedor = f.fornecedor, nif = f.nif, numero = f.numero, data = f.data, data_pag = f.data_pag, base = f.base, iva = f.iva, total = f.total,
         status = f.status, centro_custo = f.centro_custo, linhas = coalesce(f.linhas, '[]'::jsonb), guias_ref = coalesce(f.guias_ref, '[]'::jsonb)
    from faturas f
    where g.origem_id = f.id and not g.teste
      and (g.linhas, g.guias_ref, g.base, g.data, g.centro_custo, g.status, g.nif, g.total) is distinct from (coalesce(f.linhas, '[]'::jsonb), coalesce(f.guias_ref, '[]'::jsonb), f.base, f.data, f.centro_custo, f.status, f.nif, f.total);
  get diagnostics n_atual = row_count;
  return jsonb_build_object('novas', n_novas, 'atualizadas', n_atual);
end $$;
revoke all on function gt_importar_faturas() from public, anon;
grant execute on function gt_importar_faturas() to authenticated, service_role;

